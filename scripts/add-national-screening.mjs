  // "...올라 있어 법인명까지" 등) 문구를 통째로 나열하면 곧 빠뜨린다. 그래서
  // 여는 문장 뒤에 이어지는 부연 문장을 **시작 단어**로 잡아 반복 매칭한다.
  // 여기 없는 시작 단어로 새 문장을 쓰면 제거에 실패해 문구가 중복 삽입되므로,
