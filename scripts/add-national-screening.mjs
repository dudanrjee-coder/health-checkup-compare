/** 제거 정규식이 아는 후속 문장 시작 단어. 위 OBSOLETE_PATTERNS와 짝을 이룬다. */
const ALLOWED_SENTENCE_STARTS = [
  "명단에는",
  "명단에 있는",
  "공식 홈페이지",
  "최초 등록 시",
  "법인명",
  "정부가",
];

/**
 * 2026-08-22 서울 10곳 등록 때 실제로 겪은 사고를 막기 위한 가드(29번 항목).
 * 후속 문장이 위 시작 단어로 시작하지 않거나 문장 안에 마침표가 있으면
 * 제거 정규식이 걷어내지 못해 재실행할 때마다 문구가 중복 누적된다.
 * 그때는 3회 실행 후 바이트 비교(15번 항목)로 뒤늦게 발견했으므로,
 * 아예 실행 시작 시점에 터뜨려 잘못된 문구가 데이터에 닿지 못하게 한다.
 */
function assertRemovable(byId) {
  const problems = [];
  for (const [id, sentence] of Object.entries(byId)) {
    const head = sentence.match(/^국가건강검진 지정기관\([^)]*\)\.\s*/);
    if (!head) {
      problems.push(id + ': 여는 문장이 "국가건강검진 지정기관(...)." 형태가 아니다');
      continue;
    }
    const rest = sentence.slice(head[0].length);
    if (!rest) continue;
    for (const part of rest.split(". ")) {
      const body = part.replace(/\.$/, "");
      if (!body) continue;
      if (!ALLOWED_SENTENCE_STARTS.some((p) => body.startsWith(p))) {
        problems.push(id + ': 시작 단어 위반 -> "' + body.slice(0, 24) + '..."');
      }
      if (body.includes(".")) {
        problems.push(id + ': 문장 안에 마침표 -> "' + body.slice(0, 24) + '..."');
      }
    }
  }
  if (problems.length > 0) {
    throw new Error(
      "DESIGNATED_SENTENCE_BY_ID 문구가 제거 패턴과 맞지 않습니다(재실행 시 중복 누적됨):\n  " +
        problems.join("\n  ")
    );
  }
}

assertRemovable(DESIGNATED_SENTENCE_BY_ID);

function stripObsolete(note) {
  return OBSOLETE_PATTERNS.reduce(
    (text, pattern) => text.replace(pattern, ""),
    note ?? ""
  ).trim();
}

/**
 * 위 assertRemovable은 DESIGNATED_SENTENCE_BY_ID만 본다. 그래서 NOT_DESIGNATED와
 * UNDETERMINED 문구는 제거 패턴과 어긋나도 아무도 잡아 주지 않았고, 새 문구를 넣으면
 * 재실행 때마다 조용히 중복 누적될 수 있었다(2026-08-23, 30번 항목에서 발견).
 *
 * 시작 단어 검사 같은 간접 규칙 대신 **문구를 stripObsolete에 그대로 통과시켜 본다.**
 * 빈 문자열로 지워지지 않으면 그 문구는 재실행 시 걷어내지지 않는다는 뜻이다.
 * 세 맵을 모두 같은 방식으로 검사하므로 앞으로 어떤 형태를 새로 만들어도 여기서 걸린다.
 */
function assertStrippable(maps) {
  const problems = [];
  for (const [mapName, map] of Object.entries(maps)) {
    for (const [id, sentence] of Object.entries(map)) {
      const left = stripObsolete(sentence);
      if (left !== "") {
        problems.push(
          `${mapName}.${id}: 제거 후 "${left.slice(0, 40)}..."가 남는다`
        );
      }
    }
  }
  if (problems.length > 0) {
    throw new Error(
      "국가검진 문구가 OBSOLETE_PATTERNS로 완전히 제거되지 않습니다(재실행 시 중복 누적됨):\n  " +
        problems.join("\n  ")
    );
  }
}

assertStrippable({ NOT_DESIGNATED, UNDETERMINED, DESIGNATED_SENTENCE_BY_ID });
assertStrippable({ DESIGNATED_SENTENCE: { _default: DESIGNATED_SENTENCE } });

function withSentence(note, sentence) {
  const base = stripObsolete(note);
  if (!base) return sentence;
  return base.endsWith(".") || base.endsWith("음")
    ? `${base} ${sentence}`
    : `${base}. ${sentence}`;
}

/** region 객체는 원본 파일처럼 한 줄로 유지한다. */
function formatJson(hospitals) {
  return (
    JSON.stringify(hospitals, null, 2).replace(
      /"region": \{\s*\n\s*"sido": (".*?"),\s*\n\s*"sigungu": (".*?")\s*\n\s*\}/g,
      '"region": { "sido": $1, "sigungu": $2 }'
    ) + "\n"
  );
}

async function main() {
  const hospitals = JSON.parse(await readFile(HOSPITALS_PATH, "utf8"));

  let designated = 0;
  let notDesignated = 0;
  let undetermined = 0;

  for (const hospital of hospitals) {
    const reason = NOT_DESIGNATED[hospital.id];

    if (reason) {
      hospital.nationalScreeningDesignated = false;
      hospital.note = withSentence(hospital.note, reason);
      notDesignated += 1;
      console.log(`- ${hospital.name}: 미지정`);
      continue;
    }

    const unknown = UNDETERMINED[hospital.id];
    if (unknown) {
      delete hospital.nationalScreeningDesignated;
      hospital.note = withSentence(hospital.note, unknown);
      undetermined += 1;
      console.log(`? ${hospital.name}: 미확인`);
      continue;
    }

    hospital.nationalScreeningDesignated = true;
    hospital.note = withSentence(
      hospital.note,
      DESIGNATED_SENTENCE_BY_ID[hospital.id] ?? DESIGNATED_SENTENCE
    );
    designated += 1;
  }

  await writeFile(HOSPITALS_PATH, formatJson(hospitals), "utf8");
  console.log(
    `\n병원 ${hospitals.length}곳 / 지정 ${designated}곳 / 미지정 ${notDesignated}곳 / 미확인 ${undetermined}곳`
  );
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
